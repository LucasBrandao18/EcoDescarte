export const seedWastes: Waste[] = entries.map(
  ([
    id,
    name,
    category,
    synonyms,
    disposalInstructions,
    preparation,
    dangerous = false,
    recyclable = true,
  ]) => ({
    id,
    name,
    normalizedName: name
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase(),
    synonyms,
    category,
    description: `Orientação de descarte para ${name.toLowerCase()}. Confirme as condições de recebimento no ponto escolhido.`,
    recyclable,
    dangerous,
    commonTrash: false,
    disposalInstructions,
    preparation,
    environmentalImpact: dangerous
      ? 'A destinação inadequada pode contaminar o solo e a água e expor pessoas a substâncias perigosas.'
      : 'A destinação correta recupera materiais, reduz o desperdício e diminui a pressão sobre recursos naturais.',
    icon: category,
    image: '',
    active: true,
    createdAt: timestamp,
    updatedAt: timestamp,
  }),
);

